// Builds css/cafoo-tokens.css: runs Terrazzo (terrazzo.config.mjs), then
// re-indents its output, adds color-scheme to each mode block and appends the
// Tailwind @theme block that turns the semantic tokens into utility classes
// and switches Tailwind's own palette, type sizes, radii and fonts off.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { PACKAGE_ROOT, loadTokens } from './tokens.mjs';

export const CSS_FILE = resolve(PACKAGE_ROOT, 'css/cafoo-tokens.css');
const TZ = resolve(PACKAGE_ROOT, 'node_modules/.bin/tz');

/** Run Terrazzo into a scratch directory and return the finished CSS. */
export function generateCSS() {
	const out = mkdtempSync(join(tmpdir(), 'cafoo-tokens-'));
	try {
		execFileSync(TZ, ['build'], { cwd: PACKAGE_ROOT, env: { ...process.env, CAFOO_TOKENS_OUT: out }, stdio: 'pipe' });
		const raw = readFileSync(join(out, 'cafoo-tokens.css'), 'utf8');
		return `${header()}\n${reindent(withColorScheme(stripBanner(raw)))}\n${themeBlock(loadTokens())}`;
	} finally {
		rmSync(out, { recursive: true, force: true });
	}
}

function header() {
	return [
		'/* Generated by `pnpm -F @cafoo/design-tokens build` from packages/design-tokens/tokens/*.tokens.json.',
		' * Do not edit; change the tokens and rebuild. Only the semantic tier is here: primitives never reach CSS.',
		' * The @theme block at the end is the complete list of design classes that exist in apps/web. */',
	].join('\n');
}

/** Terrazzo's own banner; ours is above it. */
function stripBanner(css) {
	return css.replace(/^\/\* -+\n\s*\*\s+Autogenerated by .*\n\s*\* -+ \*\/\n*/m, '');
}

function withColorScheme(css) {
	return css
		.replace(/^:root \{\n/m, ':root {\n\tcolor-scheme: light;\n')
		.replace(/^:root\[data-theme='dark'\] \{\n/m, ":root[data-theme='dark'] {\n\tcolor-scheme: dark;\n")
		.replace(/^(\t:root:not\(\[data-theme='light'\]\) \{)\n/m, '$1\n\t\tcolor-scheme: dark;\n');
}

/** Terrazzo's printer leaves the first declaration of each block unindented; normalise everything to tabs by nesting depth. */
function reindent(css) {
	const lines = css.split('\n');
	const outLines = [];
	let depth = 0;
	for (const rawLine of lines) {
		const line = rawLine.trim();
		if (line === '') {
			outLines.push('');
			continue;
		}
		if (line.startsWith('}')) depth = Math.max(0, depth - 1);
		outLines.push('\t'.repeat(depth) + line);
		if (line.endsWith('{')) depth++;
	}
	return outLines.join('\n').trimEnd() + '\n';
}

function fontStack(families) {
	return families.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
}

/** The Tailwind theme: every token as a class, Tailwind's defaults off. */
export function themeBlock(tokens) {
	const byGroup = (group) => [...tokens.values()].filter((t) => t.path[0] === group);
	const lines = ['@theme inline {'];
	lines.push('\t/* Colours: bg-*, text-*, border-*, fill-*, stroke-*, ring-*, divide-*. Tailwind\'s palette is off. */');
	lines.push('\t--color-*: initial;');
	for (const t of byGroup('color')) lines.push(`\t--color-${t.path[1]}: var(--${t.path[1]});`);
	for (const t of byGroup('role')) lines.push(`\t--color-role-${t.path[1]}: var(--role-${t.path[1]});`);
	lines.push('');
	lines.push("\t/* Fonts: font-sans, font-display, font-mono. */");
	lines.push('\t--font-*: initial;');
	for (const t of byGroup('font')) lines.push(`\t--font-${t.path[1]}: ${fontStack(t.$value)};`);
	lines.push('');
	lines.push("\t/* Type scale: text-micro … text-display carry size, line height, tracking and weight. Tailwind's text-sm etc. are off. */");
	lines.push('\t--text-*: initial;');
	for (const t of byGroup('type')) {
		const n = t.path[1];
		lines.push(`\t--text-${n}: var(--type-${n}-font-size);`);
		lines.push(`\t--text-${n}--line-height: var(--type-${n}-line-height);`);
		lines.push(`\t--text-${n}--letter-spacing: var(--type-${n}-letter-spacing);`);
		lines.push(`\t--text-${n}--font-weight: var(--type-${n}-font-weight);`);
	}
	lines.push('');
	lines.push("\t/* Radii: rounded-sm, rounded-md, rounded-lg, rounded-xl (rounded-full stays). --radius-card/--radius-btn are legacy names for app.css. */");
	lines.push('\t--radius-*: initial;');
	for (const t of byGroup('shape')) lines.push(`\t--radius-${t.path[1]}: var(--shape-${t.path[1]});`);
	lines.push('}');
	return lines.join('\n') + '\n';
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
	const css = generateCSS();
	writeFileSync(CSS_FILE, css);
	console.log(`wrote ${CSS_FILE} (${css.split('\n').length} lines)`);
}
